"""e93: human-sized forcing chains at M=40 for the order gadget OG(40).

Fact being explained (e87/e89/e90): OG(40) is UNSAT.  Attack-incremental
analysis (see data/og40_backbone.txt) showed attacks 1-13 (all seven
15-attacks + 16-attacks j=1..6) FORCE the order 47<78, while attack
#14 = (78,47) demands 78<47.  This script reconstructs a pencil-shaped
derivation DAG for 47<78.

Instance: 59-triple MUS (e90 at M=40) + full transitivity over its 37
values + attacks as selector-guarded units.  AP triple (a,b,c) forbids
position patterns pos(a)<pos(b)<pos(c) and pos(c)<pos(b)<pos(a), i.e.
clauses  ~(a<b & b<c)  and  ~(c<b & b<a).

Pipeline
  1. verify: SAT under attacks 1-13; forces 47<78; UNSAT with #14;
     cross-check the forced backbone against data/og40_backbone.txt.
  2. S* = deletion-minimal subset of (attacks 1-13 + 59 triples) forcing
     47<78.  Measured: 8 attacks + ALL 59 triples (consistent with MUS
     minimality -- the whole refutation factors through the target).
  3. obstruction measurements (why no linear chain exists):
     unit propagation from the attack units derives NOTHING; failed-literal
     saturation (SLUP) derives NOTHING; smallest lemma-free deletion-minimal
     support over all forced literals has ~34 constraints.
  4. pass A: greedy sound derivation order -- repeatedly derive the
     remaining forced literal with the smallest deletion-minimal support
     over (constraints + already-derived literals as unit lemmas).
  5. cone = ancestors of 47<78 in the pass-A DAG; pass B re-shrinks every
     cone node with lemma pool restricted to EARLIER CONE nodes only
     (multi-restart deletion), then re-extracts the cone.
  6. per-node case-split certificate: minimal decision tree over pair
     orders refuting (support + negation of node), leaves closed by unit
     propagation (triple clauses + transitivity + support units/lemmas).
  7. outputs: data/e93_dag_M40.json + notes/28-chains-M40.md.
"""
import itertools, json, random, sys, time
from collections import defaultdict
from pysat.solvers import Cadical195

random.seed(197)
M = 40
LO, HI = M, 2 * M
TARGET = (47, 78)

# 59-triple MUS at M=40, regenerated by:
#   .venv/bin/python experiments/e90_og_mus_gen.py 40
TRIPS = [
    (41, 53, 65), (41, 57, 73), (42, 51, 60), (42, 57, 72), (42, 60, 78),
    (43, 57, 71), (44, 57, 70), (44, 60, 76), (44, 61, 78), (45, 53, 61),
    (45, 57, 69), (45, 61, 77), (46, 56, 66), (47, 59, 71), (47, 61, 75),
    (48, 54, 60), (48, 57, 66), (49, 57, 65), (49, 61, 73), (51, 55, 59),
    (51, 60, 69), (51, 61, 71), (53, 57, 61), (53, 58, 63), (53, 59, 65),
    (53, 61, 69), (53, 65, 77), (54, 58, 62), (54, 60, 66), (55, 59, 63),
    (55, 61, 67), (55, 65, 75), (56, 61, 66), (56, 66, 76), (57, 59, 61),
    (57, 61, 65), (57, 65, 73), (57, 66, 75), (57, 67, 77), (58, 62, 66),
    (58, 63, 68), (59, 63, 67), (59, 65, 71), (59, 66, 73), (59, 67, 75),
    (60, 66, 72), (60, 69, 78), (61, 63, 65), (61, 65, 69), (61, 66, 71),
    (61, 69, 77), (62, 66, 70), (63, 65, 67), (63, 67, 71), (63, 68, 73),
    (67, 71, 75), (68, 73, 78), (69, 71, 73), (71, 73, 75),
]
assert len(TRIPS) == 59
for (a, b, c) in TRIPS:
    assert b - a == c - b and LO < a < b < c <= HI

ATTACKS = []          # 1-indexed order: 15-attacks j=1..7, 16-attacks j=1..8
for x in (15, 16):
    for j in range(1, x // 2 + 1):
        ATTACKS.append((HI + 2 * j - x, LO + j))
assert ATTACKS[13] == (78, 47)
ATK13 = ATTACKS[:13]

VALS = sorted(set(v for t in TRIPS for v in t) | set(v for a in ATTACKS for v in a))
assert len(VALS) == 37
idx = {v: i for i, v in enumerate(VALS)}
n = len(VALS)
var, c = {}, 0
for i in range(n):
    for j in range(i + 1, n):
        c += 1
        var[(i, j)] = c
def o(u, w):
    i, j = idx[u], idx[w]
    return var[(i, j)] if i < j else -var[(j, i)]

nv = c
cl = []
for i in range(n):                                   # transitivity, hard
    for j in range(i + 1, n):
        for k in range(j + 1, n):
            a_, b_, c_ = var[(i, j)], var[(j, k)], var[(i, k)]
            cl.append([-a_, -b_, c_])
            cl.append([a_, b_, -c_])
asel, tsel = {}, {}
for i, (z, y) in enumerate(ATTACKS):
    nv += 1; asel[i] = nv
    cl.append([-nv, o(z, y)])
for t in TRIPS:
    a, b, cc = t
    nv += 1; tsel[t] = nv
    cl.append([-nv, -o(a, b), -o(b, cc)])
    cl.append([-nv, -o(cc, b), -o(b, a)])
sol = Cadical195(bootstrap_with=cl)
BASE13 = [asel[i] for i in range(13)] + [tsel[t] for t in TRIPS]

def forced(sels, L):
    return not sol.solve(assumptions=list(sels) + [-o(*L)])

def shrink1(sels, L):
    work = list(sels)
    i = 0
    while i < len(work):
        cand = work[:i] + work[i + 1:]
        if forced(cand, L):
            work = cand
        else:
            i += 1
    return work

def shrink(sels, L, tries=1):
    best = shrink1(sels, L)
    for _ in range(tries - 1):
        p = list(sels)
        random.shuffle(p)
        s = shrink1(p, L)
        if len(s) < len(best):
            best = s
    return best

t0 = time.time()
# ---------- step 1: verification + backbone cross-check ----------
assert sol.solve(assumptions=BASE13), "SAT under attacks 1-13"
assert forced(BASE13, TARGET), "47<78 forced under attacks 1-13"
assert not sol.solve(assumptions=BASE13 + [asel[13]]), "UNSAT with #14"
backbone13 = []
for u, w in itertools.combinations(VALS, 2):
    if not sol.solve(assumptions=BASE13 + [-o(u, w)]):
        backbone13.append((u, w))
    elif not sol.solve(assumptions=BASE13 + [o(u, w)]):
        backbone13.append((w, u))
try:
    ref = set()
    with open("data/og40_backbone.txt") as fh:
        for ln in fh:
            ln = ln.strip()
            if "<" in ln and ln[0].isdigit():
                u, w = map(int, ln.split("<"))
                ref.add((u, w))
    bb = set(backbone13) - set(ATK13)
    print(f"[1] verified; backbone under 1-13: {len(backbone13)} literals "
          f"({len(bb)} non-axiom); og40_backbone.txt has {len(ref)}; "
          f"agreement: {len(bb & ref)} shared, {len(bb - ref)} extra, "
          f"{len(ref - bb)} missing ({time.time()-t0:.1f}s)", flush=True)
except FileNotFoundError:
    print("[1] verified (og40_backbone.txt not found for cross-check)",
          flush=True)

# ---------- step 2: S* ----------
STAR = shrink(BASE13, TARGET)
star_ai = sorted(i for i in range(13) if asel[i] in STAR)
star_tr = sorted(t for t in TRIPS if tsel[t] in STAR)
print(f"[2] S* forcing 47<78: {len(star_ai)} attacks + {len(star_tr)} "
      f"triples; attacks kept: "
      f"{[(i+1, ATTACKS[i]) for i in star_ai]}", flush=True)

# ---------- step 3: obstruction measurements ----------
rules_all = defaultdict(list)
for t in TRIPS:
    a, b, cc = t
    rules_all[(a, b)].append(((cc, b), t))
    rules_all[(b, cc)].append(((b, a), t))
    rules_all[(cc, b)].append(((a, b), t))
    rules_all[(b, a)].append(((b, cc), t))

def up(facts, rules):
    facts = set(facts)
    by_f, by_s = defaultdict(set), defaultdict(set)
    for f in facts:
        by_f[f[0]].add(f); by_s[f[1]].add(f)
    queue = list(facts)
    while queue:
        f = queue.pop()
        u, v = f
        new = [cn for cn, _ in rules[f]]
        new += [(u, g[1]) for g in by_f[v]]
        new += [(g[0], v) for g in by_s[u]]
        for h in new:
            if h not in facts:
                if (h[1], h[0]) in facts:
                    return None
                facts.add(h)
                by_f[h[0]].add(h); by_s[h[1]].add(h)
                queue.append(h)
    return facts

F0 = up(set(ATK13), rules_all)
extra_up = len(F0) - 13
# SLUP: failed-literal saturation
F = set(F0)
slup_added = 0
while True:
    prog = False
    for p in itertools.permutations(VALS, 2):
        if p in F or (p[1], p[0]) in F:
            continue
        if up(F | {p}, rules_all) is None:
            F = up(F | {(p[1], p[0])}, rules_all)
            assert F is not None
            slup_added += 1
            prog = True
    if not prog:
        break
raw_sup = {}
for L in backbone13:
    if L in set(ATK13):
        continue
    raw_sup[L] = shrink(BASE13, L, tries=4)
min_raw = min(len(s) for s in raw_sup.values())
print(f"[3] obstructions: UP from attacks derives {extra_up} facts; SLUP "
      f"adds {slup_added}; smallest lemma-free minimal support over all "
      f"{len(raw_sup)} forced literals: {min_raw} constraints "
      f"({time.time()-t0:.1f}s)", flush=True)

# lemma selectors
lsel = {}
lem_cl = []
for L in backbone13:
    nv += 1; lsel[L] = nv
    lem_cl.append([-nv, o(*L)])
sol.append_formula(lem_cl)
KIND = {}
for i, s in asel.items():
    KIND[s] = ("A", i)
for t, s in tsel.items():
    KIND[s] = ("T", t)
for L, s in lsel.items():
    KIND[s] = ("L", L)

def fmt(s):
    k, v = KIND[s]
    if k == "A":
        return f"A{v+1}:{ATTACKS[v][0]}<{ATTACKS[v][1]}"
    if k == "T":
        return f"T{v}"
    return f"{v[0]}<{v[1]}"

# ---------- step 4: pass A greedy order ----------
atkset = set(ATK13)
D = [L for L in backbone13 if L in atkset]
rest = [L for L in backbone13 if L not in atkset]
orderA = []
while rest:
    best = None
    for L in rest:
        cand = ([tsel[t] for t in TRIPS] + [asel[i] for i in range(13)] +
                [lsel[L2] for L2 in D])
        s = shrink(cand, L)
        if best is None or len(s) < len(best[1]):
            best = (L, s)
            if len(s) <= 2:
                break
    L, s = best
    D.append(L)
    rest.remove(L)
    orderA.append((L, s))
print(f"[4] pass A: {len(orderA)} literals derived; support sizes "
      f"{sorted(set(len(s) for _, s in orderA))} ({time.time()-t0:.1f}s)",
      flush=True)

# ---------- step 5: cone + pass B ----------
supA = dict(orderA)
posA = {L: i for i, (L, _) in enumerate(orderA)}
def ancestors(target, sup):
    anc, stack = set(), [target]
    while stack:
        L = stack.pop()
        if L in anc or L in atkset:
            continue
        anc.add(L)
        for s in sup[L]:
            k, v = KIND[s]
            if k == "L" and v not in atkset:
                stack.append(v)
    return anc

cone = sorted(ancestors(TARGET, supA), key=lambda L: posA[L])
# Checked separately (see notes): the heavy trio below serves only 51<61,
# and 51<61 certifies from {66<53} + attacks alone with 3 splits -- so ban
# the trio from lemma pools and let it fall out of the cone.
EXCLUDE = {(67, 46), (71, 42), (71, 44)}
supB = {}
for L in cone:
    pool = [lsel[L2] for L2 in cone
            if posA[L2] < posA[L] and L2 not in EXCLUDE]
    cand = [tsel[t] for t in TRIPS] + [asel[i] for i in range(13)] + pool
    supB[L] = shrink(cand, L, tries=24 if len(supA[L]) > 6 else 4)
cone2 = sorted(ancestors(TARGET, supB), key=lambda L: posA[L])
supB = {L: supB[L] for L in cone2}
print(f"[5] cone: pass A {len(cone)} nodes -> pass B {len(cone2)} nodes; "
      f"heavy (>4): {sum(1 for L in cone2 if len(supB[L]) > 4)} "
      f"({time.time()-t0:.1f}s)", flush=True)

depth = {}
for L in cone2:
    deps = [KIND[s][1] for s in supB[L]
            if KIND[s][0] == "L" and KIND[s][1] not in atkset]
    depth[L] = 1 + max([depth[d] for d in deps], default=0)
DEPTH = depth[TARGET]

# ---------- step 6: certificates ----------
from collections import deque

def up_traced(seed, rules):
    """BFS unit propagation with reasons; returns (reason, conflict_fact).
    reason[f] = None (seed) | ('T', triple, antecedent) | ('X', f1, f2)."""
    reason = {f: None for f in seed}
    by_f, by_s = defaultdict(set), defaultdict(set)
    for f in seed:
        by_f[f[0]].add(f); by_s[f[1]].add(f)
    q = deque(seed)
    while q:
        f = q.popleft()
        u, v = f
        cand = [(cn, ('T', t, f)) for cn, t in rules[f]]
        cand += [((u, g[1]), ('X', f, g)) for g in list(by_f[v])]
        cand += [((g[0], v), ('X', g, f)) for g in list(by_s[u])]
        for h, r in cand:
            if h in reason:
                continue
            reason[h] = r
            if (h[1], h[0]) in reason:
                return reason, h
            by_f[h[0]].add(h); by_s[h[1]].add(h)
            q.append(h)
    return reason, None

def chain_lines(seed, rules):
    reason, conflict = up_traced(seed, rules)
    assert conflict is not None
    rev = (conflict[1], conflict[0])
    lines, seen = [], set()
    def anc(f):
        if f in seen:
            return
        seen.add(f)
        r = reason[f]
        if r is None:
            return
        if r[0] == 'T':
            anc(r[2])
            a = r[2]
            lines.append(f"{a[0]}<{a[1]} + AP{r[1]} => {f[0]}<{f[1]}")
        else:
            anc(r[1]); anc(r[2])
            f1, f2 = r[1], r[2]
            lines.append(f"{f1[0]}<{f1[1]} & {f2[0]}<{f2[1]} => "
                         f"{f[0]}<{f[1]}")
    anc(conflict); anc(rev)
    lines.append(f"contradiction: {conflict[0]}<{conflict[1]} vs "
                 f"{rev[0]}<{rev[1]}")
    return lines

def certificate(L, sup):
    trips = [KIND[s][1] for s in sup if KIND[s][0] == "T"]
    units = [ATTACKS[KIND[s][1]] for s in sup if KIND[s][0] == "A"]
    units += [KIND[s][1] for s in sup if KIND[s][0] == "L"]
    rules = defaultdict(list)
    for t in trips:
        a, b, cc = t
        rules[(a, b)].append(((cc, b), t))
        rules[(b, cc)].append(((b, a), t))
        rules[(cc, b)].append(((a, b), t))
        rules[(b, a)].append(((b, cc), t))
    vals = sorted(set(v for t in trips for v in t) |
                  set(v for uu in units for v in uu) | set(L))
    pivots = []
    for t in trips:
        for p in ((t[0], t[1]), (t[1], t[2])):
            if p not in pivots:
                pivots.append(p)
    for p in itertools.combinations(vals, 2):
        if p not in pivots:
            pivots.append(p)
    seed = frozenset(units) | {(L[1], L[0])}
    def go(sd, d):
        F = up(sd, rules)
        if F is None:
            return ('leaf', sd)
        if d == 0:
            return None
        for p in pivots:
            if p in F or (p[1], p[0]) in F:
                continue
            a1 = go(sd | {p}, d - 1)
            if a1 is None:
                continue
            a2 = go(sd | {(p[1], p[0])}, d - 1)
            if a2 is None:
                continue
            return ('split', p, a1, a2)
        return None
    for d in range(0, 5):
        tr = go(seed, d)
        if tr is not None:
            return d, tr, rules
    return None, None, None

def tree_txt(tr, rules, ind):
    if tr[0] == 'leaf':
        return [" " * ind + ln for ln in chain_lines(tr[1], rules)]
    _, (p, q), a1, a2 = tr
    out = [" " * ind + f"case {p}<{q}:"]
    out += tree_txt(a1, rules, ind + 2)
    out += [" " * ind + f"case {q}<{p}:"]
    out += tree_txt(a2, rules, ind + 2)
    return out

certs = {}
for L in cone2:
    d, tr, rl = certificate(L, supB[L])
    assert tr is not None, f"no certificate within 4 splits for {L}"
    certs[L] = (d, tr, rl)
maxsplit = max(d for d, _, _ in certs.values())
print(f"[6] certificates: max case splits per node {maxsplit} "
      f"({time.time()-t0:.1f}s)", flush=True)

# ---------- step 7: outputs ----------
def lit_s(L):
    return f"{L[0]}<{L[1]}"

nodes = []
for L in sorted(cone2, key=lambda L: (depth[L], posA[L])):
    sup = supB[L]
    nodes.append({
        "literal": lit_s(L),
        "depth": depth[L],
        "attacks": [fmt(s) for s in sup if KIND[s][0] == "A"],
        "triples": [str(KIND[s][1]) for s in sup if KIND[s][0] == "T"],
        "intermediates": [lit_s(KIND[s][1]) for s in sup
                          if KIND[s][0] == "L"],
        "support_size": len(sup),
        "raw_support_size": len(raw_sup[L]),
        "case_splits": certs[L][0],
    })
summary = {
    "M": M, "target": lit_s(TARGET), "dag_nodes": len(cone2),
    "dag_depth": DEPTH, "max_case_splits": maxsplit,
    "attack_indexing": "1-indexed generation order; #1-7 are 15-attacks "
                       "j=1..7 (guard 65+2j before 40+j), #8-15 are "
                       "16-attacks j=1..8 (guard 64+2j before 40+j)",
    "S_star": {"attacks": [f"A{i+1}:{lit_s(ATTACKS[i])}" for i in star_ai],
               "n_triples": len(star_tr)},
    "obstructions": {
        "up_from_attacks_derives": extra_up,
        "slup_adds": slup_added,
        "min_lemma_free_support": min_raw,
    },
    "nodes": nodes,
}
with open("data/e93_dag_M40.json", "w") as fh:
    json.dump(summary, fh, indent=1)
print("wrote data/e93_dag_M40.json", flush=True)

